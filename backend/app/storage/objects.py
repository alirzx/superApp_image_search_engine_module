"""Opaque UUID storage paths; never trust client filenames as filesystem paths."""
from pathlib import Path
import os


class ObjectStore:
    def __init__(self, root: Path):
        self.root=root
        self.root.mkdir(parents=True,exist_ok=True)

    def put(self, id_: str, image: bytes, thumb: bytes):
        orig=f'originals/{id_}.webp'
        mini=f'thumbnails/{id_}.webp'
        for key,data in [(orig,image),(mini,thumb)]:
            path=self.root/key
            path.parent.mkdir(parents=True,exist_ok=True)
            temp=path.with_suffix('.tmp')
            temp.write_bytes(data)
            os.replace(temp,path)
        return orig,mini

    def get(self, key: str):
        # Only keys generated by this service are used, still defend against traversal.
        path=(self.root/key).resolve()
        if not path.is_relative_to(self.root.resolve()): raise ValueError('Invalid object key')
        return path

    def remove(self, key: str):
        self.get(key).unlink(missing_ok=True)
